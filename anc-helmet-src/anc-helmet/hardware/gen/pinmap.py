def header():
    L = ["/* AUTO-GENERATED by hardware/gen/pinmap.py - the schematic uses the same table. */",
         "#ifndef BOARD_PINS_H", "#define BOARD_PINS_H", ""]
    for net, (pin, num, fn, note) in PINS.items():
        port, idx = pin[1], int(pin[2:])
        L.append(f"#define PIN_{net}_PORT  GPIO{port}   /* {pin} (LQFP100 #{num}) {fn}{' - ' + note if note else ''} */")
        L.append(f"#define PIN_{net}_PIN   {idx}u")
    L += ["", "#endif", ""]
    return "\n".join(L)


if __name__ == "__main__":
    out = os.path.join(os.path.dirname(__file__), "..", "..", "firmware", "inc", "board_pins.h")
    with open(out, "w") as fh:
        fh.write(header())
    print("wrote", os.path.normpath(out))
